"""The localization workflow operations (no argument parsing here)."""
from __future__ import annotations

import io
import zipfile
from dataclasses import dataclass, field
from pathlib import Path

from . import ftl, meta, po as pomod
from .scopes import SOURCE_LANG, Layout, Scope, core, level

ZIP_TIME = (2024, 1, 1, 0, 0, 0)  # fixed, so packs are reproducible


class ToolError(Exception):
    pass


@dataclass
class Report:
    scope: Scope
    total: int = 0
    translated: int = 0
    fuzzy: int = 0
    errors: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)

    @property
    def percent(self) -> float:
        return 100.0 * self.translated / self.total if self.total else 100.0


def _read(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8")
    except OSError as err:
        raise ToolError(f"cannot read {path}: {err}") from err


def source_messages(layout: Layout, scope: Scope) -> list[ftl.Message]:
    path = layout.source_ftl(scope)
    if scope.kind == "level" and scope.id not in layout.levels():
        raise ToolError(f"level '{scope.id}' is not registered; run: omsi level-add <stage dir>")
    if not path.is_file():
        raise ToolError(f"English source not found: {path}")
    try:
        return ftl.parse(_read(path), scope.kind)
    except ftl.FtlError as err:
        raise ToolError(f"{path}: {err}") from err


def discover_levels(layout: Layout) -> list[str]:
    return sorted(layout.levels())


def make_pot(layout: Layout, scope: Scope):
    messages = source_messages(layout, scope)
    rel = layout.source_ftl(scope).relative_to(layout.root).as_posix()
    return pomod.make_pot(messages, scope.name, rel)


def write_pot(layout: Layout, scope: Scope) -> Path:
    pot = make_pot(layout, scope)
    path = layout.pot(scope)
    pomod.save(pot, path)
    return path


def init_po(layout: Layout, lang: str, scope: Scope, force: bool = False) -> Path:
    path = layout.po(lang, scope)
    if path.exists() and not force:
        raise ToolError(f"{path} already exists (use `update` to merge a new template, or --force)")
    pot = make_pot(layout, scope)
    pomod.save(pomod.make_po(pot, lang), path)
    pomod.save(pot, layout.pot(scope))
    return path


def update_po(layout: Layout, lang: str, scope: Scope) -> tuple[Path, dict]:
    path = layout.po(lang, scope)
    if not path.is_file():
        raise ToolError(f"{path} does not exist; create it with `omsi init {lang} ...`")
    pot = make_pot(layout, scope)
    pomod.save(pot, layout.pot(scope))
    merged, stats = pomod.merge(pomod.load(path), pot)
    pomod.save(merged, path)
    return path, stats


def check_scope(layout: Layout, lang: str, scope: Scope) -> Report:
    report = Report(scope)
    messages = source_messages(layout, scope)
    source = {c: t for m in messages for c, t in m.units()}
    report.total = len(source)
    path = layout.po(lang, scope)
    if not path.is_file():
        report.warnings.append(f"no translation file {path.relative_to(layout.root)}")
        return report
    for entry in pomod.load(path):
        ctxt = entry.msgctxt or ""
        if ctxt not in source:
            report.warnings.append(f"'{ctxt}' no longer exists in the English source (run `update`)")
            continue
        if not entry.msgstr.strip():
            continue
        if "fuzzy" in entry.flags:
            report.fuzzy += 1
            report.warnings.append(f"'{ctxt}' is fuzzy (the English text changed); review it")
            continue
        errors, warnings = ftl.validate_translation(source[ctxt], entry.msgstr, scope.kind)
        if entry.msgid != source[ctxt]:
            warnings.append("msgid differs from the English source (run `update`)")
        report.errors += [f"'{ctxt}': {e}" for e in errors]
        report.warnings += [f"'{ctxt}': {w}" for w in warnings]
        if not errors:
            report.translated += 1
    return report


def compile_scope(layout: Layout, lang: str, scope: Scope, include_fuzzy: bool = False) -> tuple[str, Report]:
    """Builds the game-ready FTL for one language and scope from its .po."""
    messages = source_messages(layout, scope)
    path = layout.po(lang, scope)
    if not path.is_file():
        raise ToolError(f"{path.relative_to(layout.root)} does not exist; run `omsi init {lang} ...` first")
    translations = {}
    for entry in pomod.load(path):
        if entry.msgstr.strip() and (include_fuzzy or "fuzzy" not in entry.flags):
            translations[entry.msgctxt] = entry.msgstr
    report = Report(scope)
    out = [
        f"# Generated by `omsi compile` from translations/{lang}/{scope.po_rel()}. Do not edit by hand.",
        f"# Language: {lang}    Scope: {scope.name}",
        "",
    ]
    for m in messages:
        report.total += len(list(m.units()))
        value = None
        attrs = []
        source_units = dict(m.units())
        for ctxt, src in source_units.items():
            text = translations.get(ctxt)
            if text is None:
                continue
            errors, warnings = ftl.validate_translation(src, text, scope.kind)
            report.warnings += [f"'{ctxt}': {w}" for w in warnings]
            if errors:
                report.errors += [f"'{ctxt}': {e}" for e in errors]
                continue
            report.translated += 1
            if ctxt == m.id:
                value = text
            else:
                attrs.append((ctxt[len(m.id) + 1:], text))
        if value is None and not attrs:
            continue
        if scope.kind == "level":
            out.append(f"{m.id} = {value}")
        else:
            out.append(ftl.render_message(m.id, value, attrs, m.comment))
        out.append("")
    return "\n".join(out).rstrip("\n") + "\n", report


def import_ftl(layout: Layout, lang: str, scope: Scope, ftl_path: Path) -> tuple[Path, int]:
    """Seeds the .po of `lang` from an existing translated .ftl file."""
    try:
        theirs = {c: t for m in ftl.parse(_read(ftl_path), scope.kind) for c, t in m.units()}
    except ftl.FtlError as err:
        raise ToolError(f"{ftl_path}: {err}") from err
    path = layout.po(lang, scope)
    if not path.is_file():
        init_po(layout, lang, scope)
    po = pomod.load(path)
    count = 0
    for entry in po:
        if entry.msgctxt in theirs and not entry.msgstr.strip():
            entry.msgstr = theirs[entry.msgctxt]
            count += 1
    pomod.save(po, path)
    return path, count


def language_meta(layout: Layout, lang: str) -> tuple[Path, dict]:
    path = layout.i18n / lang / "_meta.ron"
    if not path.is_file():
        raise ToolError(f"{path.relative_to(layout.root)} is missing; create it with `omsi lang-new {lang} ...`")
    try:
        data = meta.load(path)
    except ValueError as err:
        raise ToolError(str(err)) from err
    errors, _ = meta.validate(data, lang)
    if errors:
        raise ToolError(f"{path.relative_to(layout.root)}: " + "; ".join(errors))
    return path, data


def check_fonts(layout: Layout, lang: str, data: dict) -> list[str]:
    available = set()
    for d in (layout.fonts, layout.i18n / lang / "fonts"):
        if d.is_dir():
            for p in d.iterdir():
                if p.suffix.lower() in (".ttf", ".otf"):
                    available.add(meta.normalize_font_stem(p.stem))
    return [
        f"font '{fid}' referenced by _meta.ron was not found in assets/fonts or assets/i18n/{lang}/fonts "
        f"(the game falls back to its built-in font)"
        for fid in meta.font_ids(data) if fid not in available
    ]


def build_pack(layout: Layout, lang: str, scopes: list[Scope], with_fonts: bool = False,
               include_fuzzy: bool = False) -> tuple[bytes, list[Report]]:
    meta_path, data = language_meta(layout, lang)
    files: dict[str, bytes] = {f"{lang}/_meta.ron": meta_path.read_bytes()}
    reports = []
    for scope in scopes:
        text, report = compile_scope(layout, lang, scope, include_fuzzy)
        if report.errors:
            raise ToolError(f"{scope.name}: " + "; ".join(report.errors))
        files[f"{lang}/{scope.ftl_rel()}"] = text.encode("utf-8")
        reports.append(report)
    if with_fonts:
        wanted = set(meta.font_ids(data))
        for d in (layout.fonts, layout.i18n / lang / "fonts"):
            if d.is_dir():
                for p in sorted(d.iterdir()):
                    if p.suffix.lower() in (".ttf", ".otf") and meta.normalize_font_stem(p.stem) in wanted:
                        files[f"{lang}/fonts/{p.name}"] = p.read_bytes()
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for name in sorted(files):
            info = zipfile.ZipInfo(name, ZIP_TIME)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            z.writestr(info, files[name])
    return buf.getvalue(), reports


def install_pack(layout: Layout, zip_path: Path, overwrite_meta: bool = False) -> list[str]:
    written = []
    try:
        z = zipfile.ZipFile(zip_path)
    except (OSError, zipfile.BadZipFile) as err:
        raise ToolError(f"cannot open {zip_path}: {err}") from err
    with z:
        for info in z.infolist():
            name = info.filename
            parts = name.split("/")
            if info.is_dir():
                continue
            if name.startswith("/") or ".." in parts or len(parts) < 2:
                raise ToolError(f"unsafe or malformed entry in pack: '{name}'")
            dest = layout.i18n / name
            if parts[1] == "_meta.ron" and dest.exists() and not overwrite_meta:
                continue
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_bytes(z.read(info))
            written.append(name)
    return written


def level_add(layout: Layout, stage_dir: Path, level_id: str | None = None) -> tuple[str, Path]:
    """Registers a stage source folder so its English strings can be translated.

    The English text stays where the stage author keeps it (and is compiled from
    there); nothing is copied. The level id is the stage's own id (stage.yaml)."""
    import yaml

    stage_dir = stage_dir.resolve()
    stage_yaml = stage_dir / "stage.yaml"
    if not stage_yaml.is_file():
        raise ToolError(f"{stage_dir} has no stage.yaml")
    try:
        data = yaml.safe_load(stage_yaml.read_text(encoding="utf-8")) or {}
    except (OSError, yaml.YAMLError) as err:
        raise ToolError(f"{stage_yaml}: {err}") from err
    stage_id = (data.get("stage") or {}).get("id")
    if not isinstance(stage_id, str):
        raise ToolError(f"{stage_yaml}: stage.id is missing")
    if level_id and level_id != stage_id:
        raise ToolError(f"--id '{level_id}' differs from stage.id '{stage_id}' in {stage_yaml}; "
                        f"the id of a level is its stage id")
    ftl_dir = (data.get("localization") or {}).get("ftl", "localization")
    if str(ftl_dir).endswith(".ftl"):
        raise ToolError("localization.ftl must be a folder of <locale>.ftl files to use it with omsi")
    english = stage_dir / ftl_dir / f"{SOURCE_LANG}.ftl"
    if not english.is_file():
        raise ToolError(f"{english} not found: a stage needs its English source {SOURCE_LANG}.ftl")
    try:
        ftl.parse(_read(english), "level")
    except ftl.FtlError as err:
        raise ToolError(f"{english}: {err}") from err
    try:
        rel = stage_dir.relative_to(layout.root.resolve()).as_posix()
    except ValueError as err:
        raise ToolError(f"{stage_dir} is outside the repository {layout.root}") from err
    levels = layout.levels()
    levels[stage_id] = {"dir": rel, "ftl": str(ftl_dir).replace("\\", "/")}
    layout.save_levels(levels)
    return stage_id, english


def level_remove(layout: Layout, level_id: str) -> None:
    levels = layout.levels()
    if level_id not in levels:
        raise ToolError(f"level '{level_id}' is not registered")
    del levels[level_id]
    layout.save_levels(levels)


def stats(layout: Layout, langs: list[str], scopes: list[Scope]) -> list[tuple[str, Report]]:
    rows = []
    for lang in langs:
        for scope in scopes:
            rows.append((lang, check_scope(layout, lang, scope)))
    return rows


def languages(layout: Layout) -> list[str]:
    if not layout.i18n.is_dir():
        return []
    return sorted(p.name for p in layout.i18n.iterdir() if p.is_dir() and (p / "_meta.ron").is_file()
                  and p.name != SOURCE_LANG)
